// Writes every page, case study, blog post and article as plain text to
// backend/app/chat/knowledge.md, which the AI chat assistant answers from (when AI is switched on).
// Run after changing anything in content/:  npm run content:knowledge
// CI fails if the committed file is out of date.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import ts from "typescript";

const OUT = "../backend/app/chat/knowledge.md";

// Loads one TypeScript module whose imports are type-only (content files, lib/site-text.ts).
function load(file) {
  const src = fs.readFileSync(file, "utf8");
  const { outputText } = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  });
  const module = { exports: {} };
  vm.runInNewContext(outputText, { module, exports: module.exports, require: () => ({}) });
  return module.exports;
}

const all = (dir) =>
  fs.readdirSync(`content/${dir}`).filter((f) => f.endsWith(".ts")).sort()
    .map((f) => load(path.join("content", dir, f)).default);

const { siteDocuments } = load("lib/site-text.ts");
const { mainNav, contact } = load("content/nav.ts");
const docs = siteDocuments({
  pages: all("pages"), caseStudies: all("case-studies"), blogPosts: all("blog"), articles: all("articles"),
  mainNav, contact,
});

const md = docs.map((d) => [
  `## ${d.kind === "Page" || d.kind === "Service" || d.kind === "Industry solution" ? d.title : `${d.kind}: ${d.title}`}`,
  `URL: ${d.url}`,
  ...(d.meta ? [d.meta] : []),
  `Summary: ${d.summary}`,
  "",
  ...d.lines,
].join("\n"));

const header = "<!-- Generated by frontend/scripts/export-knowledge.mjs from frontend/content. Do not edit. -->";
fs.writeFileSync(OUT, `${header}\n\n${md.join("\n\n")}\n`);
console.log(`${OUT}: ${docs.length} documents, ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
